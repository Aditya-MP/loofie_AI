package com.loofie.core.job.domain;

/** Named actions that move a job between states. Each one maps to a row in {@link TransitionTable}. */
public enum JobAction {
    SUBMIT_ORDER,
    PAYMENT_CONFIRMED,
    INVITE,
    ACCEPT,
    DECLINE,
    ACCEPT_TIMEOUT,
    APPROVE_SWAP,
    MARK_SHIPPED,
    START_DIGITAL,
    CONFIRM_RECEIVED,
    REPORT_DELIVERY_ISSUE,
    COURIER_DELIVERED,
    AUTO_START_PRODUCTION,
    RESHIP,
    RESOLVE_FALSE_CLAIM,
    /** Ops: the product reported damaged after receipt is usable; production resumes with the time that was left. */
    OPS_RESUME_PRODUCTION,
    /** Ops corrects the reason code of an earlier decision (e.g. a FALSE_CLAIM reversed). State and clocks unchanged. */
    OPS_CORRECT_REASON,
    CREATOR_WITHDRAW,
    OPS_RELEASE_CREATOR,
    START_PRODUCTION,
    SUBMIT_DRAFT,
    PRODUCTION_EXPIRED,
    REQUEST_EXTENSION,
    OPS_EXTEND,
    PREVIEW_READY,
    APPROVE,
    AUTO_APPROVE,
    REQUEST_REVISION,
    RESUBMIT,
    REJECT,
    RESOLVE_APPROVE,
    RESOLVE_REPLACE,
    RESOLVE_REFUND,
    REPLACEMENT_EXPIRED,
    PAYOUT_QUEUED,
    PAYOUT_COMPLETED,
    CLOSE,
    CANCEL
}
